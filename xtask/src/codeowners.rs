//! The protected paths (CI-15): `conventions/protected-paths.txt` is the
//! single list of what only the owner may approve. `cargo xtask codeowners`
//! writes `.github/CODEOWNERS` from it, which makes the owner the code owner
//! of every path on it; `cargo xtask check codeowners` fails when the
//! committed file differs; and `cargo xtask guard` reads the list to
//! classify a pull request.

use std::fs;
use std::io;
use std::path::Path;

use anyhow::{Context, Result, bail};

/// The list, from the root.
pub const LIST: &str = "conventions/protected-paths.txt";

/// The file the forge reads, from the root.
const CODEOWNERS: &str = ".github/CODEOWNERS";

/// Characters a pattern may not hold: the forge reads them as globs or
/// escapes, which `covers` doesn't, so a pattern with one would protect
/// less in guard than on the forge; and `#`, which starts a comment.
const SPECIAL: [char; 7] = ['*', '?', '[', ']', '\\', '!', '#'];

// REUSE-IgnoreStart
/// The generated file's header: its license, since generated files are
/// CC0-1.0 (LEGAL-08), and where it comes from.
const HEADER: &str = "# SPDX-FileCopyrightText: Kreqo contributors
# SPDX-License-Identifier: CC0-1.0

# Generated by `cargo xtask codeowners` from conventions/protected-paths.txt,
# the single list of what only the owner may approve (CI-15). Edit that list,
# then run the command; `cargo xtask check codeowners` fails when this file
# differs from what the list generates.

";
// REUSE-IgnoreEnd

/// The list of protected paths, read.
pub struct Protected {
    /// The code owner of every path on the list.
    owner: String,
    patterns: Vec<Pattern>,
}

/// A protected path pattern, rooted with `/` or a name without `/`, and
/// why it's protected.
pub struct Pattern {
    pub path: String,
    pub reason: String,
}

impl Protected {
    /// Reads the list, failing with every problem it finds, each with its
    /// line.
    pub fn parse(text: &str) -> Result<Self> {
        // ASCII spaces only, as the gate's workflow step skips lines, so
        // that the two never read the list differently.
        let mut lines = text
            .lines()
            .enumerate()
            .map(|(index, line)| (index + 1, line))
            .filter(|(_, line)| {
                let line = line.trim_ascii();
                !line.is_empty() && !line.starts_with('#')
            });
        let mut problems = Vec::new();
        let owner = match lines.next().map(|(number, line)| (number, owner(line))) {
            Some((_, Some(owner))) => owner.to_owned(),
            Some((number, None)) => {
                problems.push(format!(
                    "line {number}: the first line that isn't a comment must be `owner @login`, unindented, with one login and no team"
                ));
                String::new()
            }
            None => bail!("it names no owner and lists no path"),
        };
        let mut patterns: Vec<Pattern> = Vec::new();
        for (number, line) in lines {
            match pattern(line.trim_ascii()) {
                Ok(pattern) if patterns.iter().any(|listed| listed.path == pattern.path) => {
                    problems.push(format!("line {number}: `{}` is listed twice", pattern.path));
                }
                Ok(pattern) => patterns.push(pattern),
                Err(problem) => problems.push(format!("line {number}: {problem}")),
            }
        }
        if patterns.is_empty() {
            problems.push("it lists no path".to_owned());
        }
        if !problems.is_empty() {
            bail!("{}", problems.join("; "));
        }
        Ok(Self { owner, patterns })
    }

    /// The first pattern that covers a path, as git lists it from the root.
    pub fn covering(&self, path: &str) -> Option<&Pattern> {
        self.patterns
            .iter()
            .find(|pattern| covers(&pattern.path, path))
    }

    /// The CODEOWNERS file that makes the owner the code owner of every
    /// pattern, in the list's order.
    fn codeowners(&self) -> String {
        let lines: String = self
            .patterns
            .iter()
            .map(|pattern| format!("{} {}\n", pattern.path, self.owner))
            .collect();
        format!("{HEADER}{lines}")
    }
}

/// The owner that an `owner @login` line names: unindented, one space, then
/// a single login of letters, digits and hyphens, and no team. That is all
/// the gate's workflow step reads as the owner, so a list that passes here
/// never leaves the gate without one.
fn owner(line: &str) -> Option<&str> {
    let owner = line.trim_ascii_end().strip_prefix("owner ")?;
    let login = owner.strip_prefix('@')?;
    let valid = !login.is_empty()
        && login
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-');
    valid.then_some(owner)
}

/// A pattern line: a path rooted with `/`, or a name without `/`, then `#`
/// and its reason.
fn pattern(line: &str) -> Result<Pattern, String> {
    let (path, rest) = line.split_once(char::is_whitespace).unwrap_or((line, ""));
    let reason = rest
        .trim_start()
        .strip_prefix('#')
        .map(str::trim)
        .unwrap_or_default();
    if reason.is_empty() {
        return Err(format!(
            "`{path}` needs its reason after it, as `  # reason`"
        ));
    }
    if path.contains(SPECIAL) {
        return Err(format!(
            "`{path}` holds a glob, an escape or a `#`, which guard doesn't read as the forge does; list literal paths"
        ));
    }
    if path.ends_with('/') {
        return Err(format!(
            "`{path}` ends in `/`, which the forge reads as a folder only, so a file or link of that name would escape it; drop the `/`"
        ));
    }
    let parts = match path.strip_prefix('/') {
        Some(rooted) => rooted,
        None if path.contains('/') => {
            return Err(format!(
                "`{path}` must be rooted with a leading `/`, or be a name without `/`, which covers that name in any folder"
            ));
        }
        None => path,
    };
    if parts.split('/').any(|part| matches!(part, "" | "." | "..")) {
        return Err(format!(
            "`{path}` has an empty, `.` or `..` part, so it would cover no path git lists"
        ));
    }
    Ok(Pattern {
        path: path.to_owned(),
        reason: reason.to_owned(),
    })
}

/// Whether a pattern covers a path, as the forge reads CODEOWNERS: a
/// rooted pattern covers the file, link or folder at that path, and
/// everything in the folder; a name without `/` covers every file, link or
/// folder of that name, in any folder, and everything in it. Unlike the
/// forge, it ignores ASCII case, as a checkout on a case-insensitive file
/// system does, so guard may protect more than the forge, never less.
fn covers(pattern: &str, path: &str) -> bool {
    let pattern = pattern.to_ascii_lowercase();
    let path = path.to_ascii_lowercase();
    match pattern.strip_prefix('/') {
        Some(rooted) => path == rooted || is_inside(&path, rooted),
        None => path.split('/').any(|part| part == pattern),
    }
}

/// Whether a path lies inside a folder, both from the root.
fn is_inside(path: &str, folder: &str) -> bool {
    path.strip_prefix(folder)
        .is_some_and(|rest| rest.starts_with('/'))
}

/// Writes `.github/CODEOWNERS` from the list.
pub fn write(root: &Path) -> Result<()> {
    let text = generate(root)?;
    let path = root.join(CODEOWNERS);
    if let Some(folder) = path.parent() {
        fs::create_dir_all(folder)
            .with_context(|| format!("couldn't create {}", folder.display()))?;
    }
    fs::write(&path, text).with_context(|| format!("couldn't write {}", path.display()))?;
    println!("Wrote {} from {LIST}.", path.display());
    Ok(())
}

/// The `codeowners` step of `cargo xtask check`: fails unless
/// `.github/CODEOWNERS` is what the list generates. Line endings aside: a
/// Windows checkout may turn them into CRLF, which the forge reads alike.
pub fn check(root: &Path) -> Result<()> {
    let expected = generate(root)?;
    let path = root.join(CODEOWNERS);
    let committed = match fs::read_to_string(&path) {
        Ok(text) => text,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            bail!(
                "{} is missing; run `cargo xtask codeowners`",
                path.display()
            )
        }
        Err(error) => {
            return Err(error).with_context(|| format!("couldn't read {}", path.display()));
        }
    };
    if committed.replace("\r\n", "\n") != expected {
        bail!(
            "{} differs from what {LIST} generates; run `cargo xtask codeowners`",
            path.display()
        );
    }
    println!("{CODEOWNERS} is what {LIST} generates.");
    Ok(())
}

/// The CODEOWNERS file that the list in the checkout generates.
fn generate(root: &Path) -> Result<String> {
    let path = root.join(LIST);
    let text =
        fs::read_to_string(&path).with_context(|| format!("couldn't read {}", path.display()))?;
    let protected =
        Protected::parse(&text).with_context(|| format!("{} is invalid", path.display()))?;
    Ok(protected.codeowners())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scratch::Scratch;

    /// A list with a comment, a blank line, a folder, a file and a name.
    const VALID: &str = "# Protected.\n\nowner @owner\n/conventions  # convention files\n/deny.toml  # the dependency policy\nCLAUDE.md  # agent instructions\n";

    /// The paths of a list's patterns.
    fn paths(protected: &Protected) -> Vec<&str> {
        protected
            .patterns
            .iter()
            .map(|pattern| pattern.path.as_str())
            .collect()
    }

    /// The problems a list has, as the error says them.
    fn problems(text: &str) -> String {
        match Protected::parse(text) {
            Ok(_) => "no problem".to_owned(),
            Err(error) => format!("{error:#}"),
        }
    }

    #[test]
    fn reads_the_owner_and_each_pattern_with_its_reason() -> Result<()> {
        let protected = Protected::parse(VALID)?;
        assert_eq!(protected.owner, "@owner");
        assert_eq!(
            paths(&protected),
            ["/conventions", "/deny.toml", "CLAUDE.md"]
        );
        let reasons: Vec<&str> = protected
            .patterns
            .iter()
            .map(|pattern| pattern.reason.as_str())
            .collect();
        assert_eq!(
            reasons,
            [
                "convention files",
                "the dependency policy",
                "agent instructions"
            ]
        );
        // Indented comments and blank lines, CRLF line endings, spaces
        // after the owner, an indented pattern and a tab before the reason.
        let protected = Protected::parse(
            "  # A comment.\r\n \t\r\nowner @Owner-1 \t\r\n  /a\t# why\r\n  # Another.\r\n",
        )?;
        assert_eq!(protected.owner, "@Owner-1");
        assert_eq!(paths(&protected), ["/a"]);
        Ok(())
    }

    /// Every problem is reported at once, each with its line.
    #[test]
    fn reports_every_problem_with_its_line() {
        assert_eq!(
            problems("owner @owner\n/a  # why\nb/c  # why\n/c\n/d #\n/a  # again\n/e/  # why\n"),
            "line 3: `b/c` must be rooted with a leading `/`, or be a name without `/`, which covers that name in any folder; line 4: `/c` needs its reason after it, as `  # reason`; line 5: `/d` needs its reason after it, as `  # reason`; line 6: `/a` is listed twice; line 7: `/e/` ends in `/`, which the forge reads as a folder only, so a file or link of that name would escape it; drop the `/`"
        );
        assert_eq!(
            problems("/a  # why\n/b  # why\n"),
            "line 1: the first line that isn't a comment must be `owner @login`, unindented, with one login and no team"
        );
        // A comment or a blank line holding a character that isn't an
        // ASCII space is neither, as the gate's step reads them too.
        assert_eq!(
            problems("\u{a0}# A comment.\nowner @owner\n/a  # why\n"),
            "line 1: the first line that isn't a comment must be `owner @login`, unindented, with one login and no team; line 2: `owner` needs its reason after it, as `  # reason`"
        );
        assert_eq!(
            problems("# Nothing.\n\n"),
            "it names no owner and lists no path"
        );
        assert_eq!(problems("owner @owner\n"), "it lists no path");
    }

    /// The gate's step reads the owner from `owner @login` alone, at the
    /// start of its line, so anything else is refused here too.
    #[test]
    fn refuses_an_owner_line_that_names_no_single_login() {
        for line in [
            "owner @",
            "owner owner",
            "owner @a @b",
            "owners @a",
            "owner",
            "owner  @a",
            "owner\t@a",
            " owner @a",
            "\towner @a",
            "owner @org/team",
            "owner @a_b",
            "owner @a.b",
            "owner @é",
            "owner @a\u{a0}",
        ] {
            assert_eq!(owner(line), None, "{line}");
        }
        assert_eq!(owner("owner @a"), Some("@a"));
        assert_eq!(owner("owner @Dara-K0 \t\r"), Some("@Dara-K0"));
    }

    /// A glob, an escape or a `#` would make guard protect less than the
    /// forge does; a trailing `/` would make the forge miss a file or link
    /// of that name; an unrooted path with a `/` in it would mean something
    /// else to the forge than either form; and an empty, `.` or `..` part
    /// would cover no path git lists. So each is refused rather than left
    /// to match less.
    #[test]
    fn refuses_patterns_that_guard_would_misread() {
        for path in [
            "/*.toml", "/a?", "/[ab]", "/a]", "/a\\b", "/!a", "/a#b", "/", "//", "/a//b", "/./a",
            "/a/../b", "/a/.", "/a/", "/a/b/", "a/", "a/b", ".", "..", "*.md",
        ] {
            assert!(
                pattern(&format!("{path}  # why")).is_err(),
                "{path} was accepted"
            );
        }
        for path in [
            "/a",
            "/a/b",
            "/.github",
            "/a.b/c..d",
            "CLAUDE.md",
            ".claude",
            "..a",
        ] {
            let read = pattern(&format!("{path}  # why"));
            assert_eq!(read.map(|pattern| pattern.path).as_deref(), Ok(path));
        }
    }

    /// A pattern covers what the forge's CODEOWNERS would: the file, link
    /// or folder at a rooted path, or of a name in any folder, and a
    /// folder's contents at any depth.
    #[test]
    fn covers_what_codeowners_covers() {
        // A file or link with a folder's name, such as a link `.claude`.
        assert!(covers("/a", "a"));
        assert!(covers("/a", "a/b"));
        assert!(covers("/a", "a/b/c"));
        assert!(!covers("/a", "ab/c"));
        assert!(!covers("/a", "ab"));
        assert!(!covers("/a", "b/a/c"));
        assert!(covers("/a/b", "a/b"));
        assert!(covers("/a/b", "a/b/c"));
        assert!(!covers("/a/b", "a/bc"));
        assert!(!covers("/a/b", "a"));
        assert!(covers("/a.md", "a.md"));
        assert!(covers("/a.md", "a.md/b"));
        assert!(!covers("/a.md", "a.mdx"));
        assert!(!covers("/a.md", "b/a.md"));
        // A name covers that name in any folder, and what a folder of that
        // name holds, but never part of a name.
        assert!(covers("a.md", "a.md"));
        assert!(covers("a.md", "b/c/a.md"));
        assert!(covers(".claude", "b/.claude/settings.json"));
        assert!(covers(".claude", ".claude"));
        assert!(!covers("a.md", "b/xa.md"));
        assert!(!covers("a.md", "a.mdx/b"));
        assert!(!covers("a.md", "b"));
    }

    /// A checkout on a case-insensitive file system, as on macOS or
    /// Windows, reads `.CLAUDE/settings.json` as `.claude/settings.json`,
    /// so guard ignores ASCII case, which the forge doesn't.
    #[test]
    fn covers_a_path_whatever_its_ascii_case() {
        assert!(covers("/A.md", "a.md"));
        assert!(covers("/a.md", "A.MD"));
        assert!(covers("/xtask", "XTask/src/guard.rs"));
        assert!(covers("CLAUDE.md", "crates/a/claude.MD"));
        assert!(covers(".claude", ".Claude/settings.json"));
        assert!(!covers("/a.md", "b.MD"));
    }

    #[test]
    fn finds_the_first_pattern_that_covers_a_path() -> Result<()> {
        let protected = Protected::parse("owner @o\n/a/b  # inner\n/a  # outer\n/c  # file\n")?;
        let covering = |path| {
            protected
                .covering(path)
                .map(|pattern| pattern.reason.as_str())
        };
        assert_eq!(covering("a/b/c"), Some("inner"));
        assert_eq!(covering("a/c"), Some("outer"));
        assert_eq!(covering("c"), Some("file"));
        assert_eq!(covering("d"), None);
        Ok(())
    }

    #[test]
    fn generates_codeowners_from_the_list() -> Result<()> {
        let text = Protected::parse(VALID)?.codeowners();
        assert_eq!(
            text,
            format!("{HEADER}/conventions @owner\n/deny.toml @owner\nCLAUDE.md @owner\n")
        );
        assert!(HEADER.contains("cargo xtask codeowners"));
        Ok(())
    }

    /// The repository's own list protects the checks, the decisions, the
    /// CI definitions, what agent sessions load and itself, including a
    /// file or link with a protected folder's name, and no product code.
    #[test]
    fn the_list_protects_the_checks_and_itself() -> Result<()> {
        let protected = Protected::parse(include_str!("../../conventions/protected-paths.txt"))?;
        assert_eq!(protected.owner, "@darakreqo");
        for path in [
            LIST,
            CODEOWNERS,
            ".github/workflows/ci.yml",
            ".github",
            "xtask/src/guard.rs",
            ".cargo/mutants.toml",
            ".config",
            ".config/nextest.toml",
            "conventions/rubric/review.md",
            "deny.toml",
            "rust-toolchain.toml",
            ".gitattributes",
            "REUSE.toml",
            "LICENSES/MIT.txt",
            "LICENSE",
            "LICENSE-MIT",
            "LICENSE-APACHE",
            "COPYING",
            "docs/decisions/DR-0001-workflow-foundation.md",
            ".mcp.json",
            "CLAUDE.md",
            "crates/a/CLAUDE.md",
            "CLAUDE.local.md",
            "crates/a/CLAUDE.local.md",
            ".claude",
            ".claude/settings.json",
            "crates/a/.claude/settings.json",
            "rustfmt.toml",
            "crates/a/.rustfmt.toml",
            "clippy.toml",
            "crates/a/src/.clippy.toml",
            "media",
            "media/logo.svg",
        ] {
            assert!(protected.covering(path).is_some(), "{path} isn't protected");
        }
        for path in [
            "Cargo.toml",
            "Cargo.lock",
            "crates/a/src/lib.rs",
            "crates/a/.gitattributes",
            "docs/handbook/README.md",
        ] {
            assert!(protected.covering(path).is_none(), "{path} is protected");
        }
        Ok(())
    }

    /// A scratch checkout whose list is `list`.
    fn checkout(list: &str) -> Result<Scratch> {
        let scratch = Scratch::new()?;
        let path = scratch.path().join(LIST);
        if let Some(folder) = path.parent() {
            fs::create_dir_all(folder)?;
        }
        fs::write(&path, list)?;
        Ok(scratch)
    }

    /// The check passes on what `write` writes, line endings aside, and
    /// fails on anything else, saying how to fix it.
    #[test]
    fn checks_codeowners_against_the_list() -> Result<()> {
        let scratch = checkout(VALID)?;
        let root = scratch.path();
        let path = root.join(CODEOWNERS);
        let Err(error) = check(root) else {
            bail!("a missing CODEOWNERS passed");
        };
        assert_eq!(
            format!("{error:#}"),
            format!(
                "{} is missing; run `cargo xtask codeowners`",
                path.display()
            )
        );
        write(root)?;
        assert_eq!(
            fs::read_to_string(&path)?,
            Protected::parse(VALID)?.codeowners()
        );
        check(root)?;
        fs::write(&path, fs::read_to_string(&path)?.replace('\n', "\r\n"))?;
        check(root)?;
        fs::write(root.join(LIST), format!("{VALID}/media  # human-only\n"))?;
        let Err(error) = check(root) else {
            bail!("a stale CODEOWNERS passed");
        };
        assert_eq!(
            format!("{error:#}"),
            format!(
                "{} differs from what {LIST} generates; run `cargo xtask codeowners`",
                path.display()
            )
        );
        Ok(())
    }

    /// A CODEOWNERS that's there but can't be read fails with the reason,
    /// rather than being reported missing.
    #[test]
    fn fails_on_a_codeowners_it_cant_read() -> Result<()> {
        let scratch = checkout(VALID)?;
        let path = scratch.path().join(CODEOWNERS);
        fs::create_dir_all(&path)?;
        let Err(error) = check(scratch.path()) else {
            bail!("an unreadable CODEOWNERS passed");
        };
        assert!(
            format!("{error:#}").starts_with(&format!("couldn't read {}", path.display())),
            "{error:#}"
        );
        Ok(())
    }

    /// Neither command writes or passes anything from a list with a
    /// problem.
    #[test]
    fn refuses_an_invalid_list() -> Result<()> {
        let scratch = checkout("owner @owner\n/b  # why\n/a\n")?;
        let root = scratch.path();
        for result in [write(root), check(root)] {
            let Err(error) = result else {
                bail!("an invalid list was used");
            };
            assert_eq!(
                format!("{error:#}"),
                format!(
                    "{} is invalid: line 3: `/a` needs its reason after it, as `  # reason`",
                    root.join(LIST).display()
                )
            );
        }
        assert!(!root.join(CODEOWNERS).exists());
        Ok(())
    }
}
